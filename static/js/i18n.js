const STORAGE_KEY = "lang";
let current = localStorage.getItem(STORAGE_KEY) || "vi";
if (!DICT[current]) current = "vi";

export function t(key) {
  return DICT[current]?.[key] ?? DICT.vi[key] ?? key;
}
export function lang() { return current; }

export function setLang(code) {
  if (!DICT[code] || code === current) {
    if (!DICT[code]) return;
  }
  current = code;
  localStorage.setItem(STORAGE_KEY, code);
  document.documentElement.lang = code;
  apply();
  window.dispatchEvent(new CustomEvent("lang-changed", { detail: code }));
}

export function apply() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll(".lang-opt").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === current);
  });
}